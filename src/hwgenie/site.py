def render_index(
    cfg: Dict[str, str],
    assignments: List[AssignmentBuild],
    macros: Optional[Dict[str, str]] = None,
    theme: str = "",
    custom_css: str = "",
    intro_html: str = "",
    handout_files: Optional[List[str]] = None,
    banner: str = "",
    favicon: str = "",
) -> str:
    if not theme:
        theme = theme_from_config(cfg)
    e = html_mod.escape
    course = cfg.get("course", "Course")
    title = cfg.get("title")
    semester = cfg.get("semester", "")
    instructor = cfg.get("instructor")
    heading = f"{course}: {title}" if title else course
    sub = " · ".join(x for x in (semester, instructor) if x)

    problemsets = [a for a in assignments if a.meta.doc_type == "problemset"]
    lessons = [a for a in assignments if a.meta.doc_type == "lesson"]
    syllabi = [a for a in assignments if a.meta.doc_type == "syllabus"]

    top_cards = []
    for a in syllabi:
        pdf = _page_pdf_name(a.meta, "")
        top_cards.append(
            f'<div class="assignment">\n'
            f'<h2><a href="{a.rel_url}">Syllabus</a></h2>\n'
            f'<div class="links">'
            f'{file_box(f"{a.rel_url}{pdf}", "Syllabus PDF")}</div>\n</div>'
        )
    for fname in handout_files or []:
        pretty = re.sub(r"[-_]+", " ", fname.rsplit(".", 1)[0]).strip().title()
        top_cards.append(
            f'<div class="assignment">\n'
            f'<h2>{e(pretty)}</h2>\n'
            f'<div class="links">'
            f'{file_box(f"handouts/{fname}", e(fname))}</div>\n</div>'
        )

    lesson_cards = []
    for a in lessons:
        num = e(a.meta.number)
        label = f"Lesson {num}"
        if a.meta.title:
            label += f": {e(latex_plain(a.meta.title))}"
        slug = _slug(a.meta.number)
        pdf = _page_pdf_name(a.meta, slug)
        lesson_cards.append(
            f'<div class="assignment">\n'
            f'<h2><a href="{a.rel_url}">{label}</a></h2>\n'
            f'<div class="links">'
            f'{file_box(f"{a.rel_url}{pdf}", "Lesson PDF")}</div>\n</div>'
        )

    cards = []
    for a in problemsets:
        n = e(a.meta.number)
        label = f"Problem Set {n}"
        if a.meta.title:
            label += f": {e(latex_plain(a.meta.title))}"
        slug = _slug(a.meta.number)
        names = _file_names(a.meta, slug)
        links = []
        if a.released:
            links.append(view_box(f"{a.rel_url}solutions.html", "Solutions"))
        links += [
            file_box(f'{a.rel_url}{names["handout_pdf"]}', "Problem Set PDF"),
            file_box(f'{a.rel_url}{names["submission"]}', "LaTeX source"),
        ]
        if a.released:
            links.append(
                file_box(f'{a.rel_url}{names["solutions_pdf"]}', "Solutions PDF")
            )
        cards.append(
            f'<div class="assignment">\n'
            f'<h2><a href="{a.rel_url}">{label}</a></h2>\n'
            f'<div class="links">{" ".join(links)}</div>\n</div>'
        )

    sections = []
    if intro_html:
        sections.append(f'<div class="intro">\n{intro_html}\n</div>')
    if top_cards:
        sections.append(
            '<h2 class="index-head" id="handouts">Handouts</h2>\n'
            + "\n".join(top_cards)
        )
    if lesson_cards:
        sections.append(
            '<h2 class="index-head" id="lessons">Lessons</h2>\n'
            + "\n".join(lesson_cards)
        )
    if cards:
        sections.append(
            '<h2 class="index-head" id="problem-sets">Problem Sets</h2>\n'
            + "\n".join(cards)
        )
    body = "\n".join(sections) if sections else "<p>Nothing posted yet.</p>"
    # Sticky nav (appears on scroll, same component as assignment pages):
    # section jumps for whichever sections exist.
    jumps = []
    if top_cards:
        jumps.append(("Handouts", "handouts"))
    if lesson_cards:
        jumps.append(("Lessons", "lessons"))
    if cards:
        jumps.append(("Problem Sets", "problem-sets"))
    scrollbar = scrollbar_html(None, "", course, jumps) if jumps else ""
    macros_json = json.dumps(macros or {}, ensure_ascii=False)
    plain_heading = re.sub(r"\$", "", heading)
    header = (
        f'<header class="doc">\n'
        f'<p class="course">{e(sub)}</p>\n'
        f"<h1>{e(heading)}</h1>\n"
        f"</header>"
    )
    # With banner art the header card floats in a full-width hero instead of
    # sitting at the top of the text column.
    hero = f'<div class="hero">\n<img src="{banner}" alt="">\n{header}\n</div>'
    icon_link = f'<link rel="icon" href="{favicon}">' if favicon else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(plain_heading)} — {e(semester)}</title>
{icon_link}
{THEME_HEAD_SCRIPT}
{katex_block(macros_json)}
<style>{theme}{CSS}{NAV_CSS}{INDEX_CSS}</style>
{f'<link rel="stylesheet" href="{custom_css}">' if custom_css else ""}
</head>
<body id="top">
{THEME_TOGGLE_HTML}
{scrollbar}
{hero if banner else ""}
<main>
{"" if banner else header}
<section>
{body}
</section>
<footer class="doc">{FOOTER_HTML}</footer>
</main>
{THEME_TOGGLE_JS}
{SCROLLBAR_JS}
</body>
</html>
"""
