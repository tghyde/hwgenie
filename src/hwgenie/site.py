"""Build the full course website from a repo of source files.

Repo layout::

    course.yml
    source/ps03/ps03.tex   (+ images alongside)
    source/ps04/ps04.tex
    ...

Output (default ``site/``)::

    index.html                      course home, lists all assignments
    ps/3/index.html                 handout (HTML)
    ps/3/problem-set-3.pdf          handout (PDF)
    ps/3/problem-set-3-submission.tex
    ps/3/solutions.html             ┐ only when the assignment's
    ps/3/problem-set-3-solutions.pdf┘ solutions are released

Release control comes from the ``solutions`` metadata key: an ISO date
(released once today >= date), ``released``, or ``manual`` (default: not
released).
"""

